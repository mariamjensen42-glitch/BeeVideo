package com.cycling.beevideo.ui.player

/**
 * 倍速档位。**M3 没有规定可选值**，这是本项目取值：只留能听出差别、又不至于听不清
 * 对白的几档 —— `0.75` 与 `1.25` 是刷剧时最常按的两档，`0.5` / `2.0` 是两端。
 *
 * 不放更多档：档位越密，"我现在到底调没调"越难从控件上看出来。
 */
internal val PLAYBACK_SPEEDS = listOf(0.5f, 0.75f, 1.0f, 1.25f, 1.5f, 2.0f)

/**
 * 档位文案，如 `1.0×`。
 *
 * 整档也补一位小数（`1` 写成 `1.0×`）：这几个字直接当按钮组里的标签，
 * `2×` 和 `0.75×` 宽度差一半，一排胶囊会显得没对齐。
 *
 * 直接用浮点转字符串，**不做 `%.2f` 格式化** —— 那会把 `0.75` 截成 `0.8`。
 */
internal fun speedLabel(speed: Float): String = "$speed×"
